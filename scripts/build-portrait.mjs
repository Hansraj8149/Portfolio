// Turns a photo into the dot-matrix data used by the hero portrait.
//
//   pnpm portrait <photo> [--crop left,top,width,height] [--cols 72]
//
// Writes src/content/portrait.ts (one intensity byte per cell, base64) and a
// preview PNG next to the photo so the crop/mask can be checked by eye.
// Works best with a head-and-shoulders photo on a plain or blurred background.
import sharp from "sharp";
import { writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const input = args.find((a) => !a.startsWith("--") && !/^\d/.test(a));
const opt = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? fallback : args[i + 1];
};
if (!input) {
  console.error("usage: pnpm portrait <photo> [--crop l,t,w,h] [--cols 72]");
  process.exit(1);
}

const cols = Number(opt("cols", 72));
const crop = opt("crop", null)?.split(",").map(Number);

let img = sharp(input).rotate();
if (crop) {
  const [left, top, width, height] = crop;
  img = img.extract({ left, top, width, height });
}
const meta = await img.clone().toBuffer({ resolveWithObject: true });
const { width: w, height: h } = meta.info;
const rows = Math.round((cols * h) / w);

const { data } = await img
  .resize(cols, rows, { fit: "fill" })
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

// A transparent PNG (background already removed) gives a clean mask via its
// alpha channel. For opaque photos fall back to dropping sky/glass (blue
// dominant) and foliage (green dominant). Edges fade either way.
const hasCutout = meta.info.channels === 4 && data.some((_, i) => i % 4 === 3 && data[i] < 250);
// Stretch brightness across the subject (5th–95th percentile) so a
// half-shadowed face still shows both sides.
const lums = [];
for (let i = 0; i < data.length; i += 4) {
  if (!hasCutout || data[i + 3] >= 128) {
    lums.push(0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2]);
  }
}
lums.sort((a, b) => a - b);
const lo = lums[Math.floor(lums.length * 0.05)];
const hi = lums[Math.floor(lums.length * 0.95)];
const norm = (l) => Math.max(0, Math.min(1, (l - lo) / (hi - lo || 1))) ** 0.7;

const out = new Uint8Array(cols * rows);
for (let y = 0; y < rows; y++) {
  for (let x = 0; x < cols; x++) {
    const i = (y * cols + x) * 4;
    const [r, g, b, a] = [data[i], data[i + 1], data[i + 2], data[i + 3]];
    const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
    if (hasCutout) {
      if (a < 128) continue;
    } else {
      const blue = b > r + 12 && b > g - 5;
      const green = g > r + 6 && g > b;
      if ((blue || green) && lum >= 70) continue;
    }
    const dx = (x / cols - 0.5) * 2;
    const dy = (y / rows - 0.45) * 2;
    const fade = Math.max(0, Math.min(1, 1.6 - Math.hypot(dx * 1.05, dy * 0.8)));
    // Brightness drives dot size; dark areas keep a faint floor so the
    // silhouette (hair, shirt) still reads on a dark background.
    const v = Math.max(0.12, norm(lum)) * fade;
    out[y * cols + x] = Math.round(v * 255);
  }
}

const target = path.resolve("src/content/portrait.ts");
writeFileSync(
  target,
  `// Generated by scripts/build-portrait.mjs — do not edit by hand.\n` +
    `export const portrait = {\n  cols: ${cols},\n  rows: ${rows},\n` +
    `  data: "${Buffer.from(out).toString("base64")}",\n};\n`
);

// Preview: render the dots as they'll roughly appear on the site.
const cell = 8;
const svg = [
  `<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell}" height="${rows * cell}">`,
  `<rect width="100%" height="100%" fill="#07090c"/>`,
];
out.forEach((v, i) => {
  if (!v) return;
  const x = (i % cols) * cell + cell / 2;
  const y = Math.floor(i / cols) * cell + cell / 2;
  svg.push(`<circle cx="${x}" cy="${y}" r="${((v / 255) * cell * 0.55).toFixed(2)}" fill="#f5a524"/>`);
});
svg.push("</svg>");
const preview = input.replace(/\.\w+$/, ".portrait-preview.png");
await sharp(Buffer.from(svg.join(""))).png().toFile(preview);
console.log(`wrote ${target} (${cols}x${rows}) and ${preview}`);
